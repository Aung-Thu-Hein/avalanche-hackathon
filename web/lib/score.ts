/**
 * SafeHold scoring — TypeScript mirror of `computeScore` in
 * src/SafeHoldScore_1.sol.
 *
 * Both must agree. The contract is the auditable version anyone can verify on
 * Snowtrace; this one runs server-side so the UI does not wait on a chain read.
 * Integer arithmetic and the same basis-point inputs are used deliberately so
 * the two cannot drift.
 *
 * All percentages are basis points: 10000 bps = 100%.
 */

export const PROXIMITY_WINDOW_DAYS = 30;
export const K1_NUM = 23;
export const K1_DEN = 10;
export const SEVERITY_BASE = 2000;
export const ACTIVITY_MAX_PENALTY = 8;
export const BASELINE_PENALTY = 18;
const BPS = 10_000;

export type ScoreInputs = {
  /** % of circulating supply unlocking, in bps (1800 = 18%) */
  unlockPercentBps: number;
  /** whole days until that unlock */
  daysUntilUnlock: number;
  /** avg price drop after similar past unlocks, in bps. 0 when unknown. */
  historicalDropBps?: number;
  /** how elevated on-chain activity is vs baseline, in bps. 0 = normal. */
  activityBps?: number;
};

/**
 * Integer division, matching Solidity's truncating `/`.
 * Using Math.floor rather than plain division is what keeps the two
 * implementations byte-for-byte in agreement.
 */
function computeScoreExact(i: ScoreInputs): number {
  const unlockPercentBps = Math.max(0, Math.min(BPS, Math.trunc(i.unlockPercentBps)));
  const daysUntilUnlock = Math.max(0, Math.trunc(i.daysUntilUnlock));
  const historicalDropBps = Math.max(0, Math.min(BPS, Math.trunc(i.historicalDropBps ?? 0)));
  const activityBps = Math.max(0, Math.min(BPS, Math.trunc(i.activityBps ?? 0)));

  const proximityWeightBps =
    daysUntilUnlock >= PROXIMITY_WINDOW_DAYS
      ? 0
      : Math.floor(((PROXIMITY_WINDOW_DAYS - daysUntilUnlock) * BPS) / PROXIMITY_WINDOW_DAYS);

  // One fraction, one division — multiply before dividing to keep precision,
  // exactly as the contract does.
  const numerator =
    unlockPercentBps * proximityWeightBps * K1_NUM * (SEVERITY_BASE + historicalDropBps);
  const denominator = 100 * BPS * K1_DEN * SEVERITY_BASE;

  const unlockPenalty = Math.floor(numerator / denominator);
  const activityPenalty = Math.floor((activityBps * ACTIVITY_MAX_PENALTY) / BPS);
  const totalPenalty = unlockPenalty + activityPenalty + BASELINE_PENALTY;

  return totalPenalty >= 100 ? 0 : 100 - totalPenalty;
}

export type Band = "safe" | "watch" | "risk";

export type Verdict = {
  score: number;
  band: Band;
  headline: string;
  detail: string;
};

/**
 * Inside this many days, an unlock is close enough that "safe to hold this
 * week" would be a false statement whatever the score says.
 */
export const IMMINENT_DAYS = 7;

function bandFromScore(score: number): Band {
  if (score >= 70) return "safe";
  if (score >= 40) return "watch";
  return "risk";
}

/**
 * The score measures how bad an unlock is. Whether it is *soon* is a separate
 * question, and the two must not be collapsed: a small unlock landing today
 * scored above 70, so the table said "Safe to hold this week" next to
 * "unlocks today" - contradicting itself on screen.
 *
 * So an imminent unlock can never be branded safe, however small it is.
 */
function band(score: number, daysUntilUnlock: number, hasUnlock: boolean): Band {
  const b = bandFromScore(score);
  if (hasUnlock && daysUntilUnlock <= IMMINENT_DAYS && b === "safe") return "watch";
  return b;
}

/** "today", "tomorrow", "in 4 days" - reads like a person wrote it. */
function whenPhrase(days: number): string {
  if (days <= 0) return "today";
  if (days === 1) return "tomorrow";
  return `in ${days} days`;
}

/**
 * The one-sentence explanation. Templated rather than generated by a model:
 * instant, free, and auditable — which matters more than phrasing variety when
 * the number it explains has to be defensible.
 */
export function verdict(
  inputs: ScoreInputs,
  opts: { hasUpcomingUnlock: boolean } = { hasUpcomingUnlock: true },
): Verdict {
  const score = computeScoreExact(inputs);
  const pct = inputs.unlockPercentBps / 100;
  const days = inputs.daysUntilUnlock;
  const b = band(score, days, opts.hasUpcomingUnlock);
  const imminent = opts.hasUpcomingUnlock && days <= IMMINENT_DAYS;

  if (!opts.hasUpcomingUnlock) {
    return {
      score,
      band: b,
      headline: "Safe to hold this week",
      detail: "No unlock scheduled in the data we track.",
    };
  }

  if (b === "safe") {
    return {
      score,
      band: b,
      headline: "Safe to hold this week",
      detail:
        days > PROXIMITY_WINDOW_DAYS
          ? `No unlock scheduled in the next ${PROXIMITY_WINDOW_DAYS} days.`
          : `Next unlock ${whenPhrase(days)}, ${fmtPct(pct)} of circulating supply.`,
    };
  }

  if (b === "watch") {
    return {
      score,
      band: b,
      // When the unlock is days away, say so in the headline. "Watch closely"
      // buries the one fact the reader needs.
      headline: imminent
        ? days <= 0
          ? "Unlocks today"
          : `Unlocks ${whenPhrase(days)}`
        : "Watch closely",
      detail: `${fmtPct(pct)} of circulating supply unlocks ${whenPhrase(days)}.`,
    };
  }

  return {
    score,
    band: b,
    headline: imminent ? "High risk — unlock imminent" : "High risk",
    detail: `${fmtPct(pct)} of circulating supply unlocks ${whenPhrase(days)}.`,
  };
}

function fmtPct(pct: number): string {
  if (pct >= 10) return `${Math.round(pct)}%`;
  return `${pct.toFixed(2).replace(/\.?0+$/, "")}%`;
}

export { computeScoreExact as computeScore };
